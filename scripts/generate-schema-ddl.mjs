// Generates idempotent schema DDL from prisma/schema.prisma — the SINGLE source
// of truth. Output (lib/schema-ddl.generated.js) is consumed by:
//   - lib/schema.ts        (runtime ensureSchema / withSchema self-heal)
//   - scripts/apply-schema.mjs (deploy-time application)
//
// Because the DDL is derived from schema.prisma, adding a Prisma field can never
// again be "forgotten" in a hand-written ALTER. This script also self-verifies
// and exits non-zero on any anomaly, so a parser regression fails the build.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const schemaPath = join(root, 'prisma', 'schema.prisma');
const outPath = join(root, 'lib', 'schema-ddl.generated.js');
const dtsPath = join(root, 'lib', 'schema-ddl.generated.d.ts');

const SCALARS = {
  String: 'TEXT',
  Boolean: 'BOOLEAN',
  Int: 'INTEGER',
  BigInt: 'BIGINT',
  Float: 'DOUBLE PRECISION',
  DateTime: 'TIMESTAMP(3)',
  Json: 'JSONB',
  Decimal: 'DECIMAL(65,30)',
};

const stripComment = (line) => {
  const i = line.indexOf('//');
  return i >= 0 ? line.slice(0, i) : line;
};

function sqlDefault(attrs, isArray) {
  if (isArray) return "DEFAULT '{}'";
  if (/@updatedAt\b/.test(attrs)) return 'DEFAULT CURRENT_TIMESTAMP';
  // now() / dbgenerated have nested parens — match them before the generic case.
  if (/@default\(now\(\)\)/.test(attrs)) return 'DEFAULT CURRENT_TIMESTAMP';
  const m = attrs.match(/@default\(([^)]*)\)/);
  if (!m) return '';
  const raw = m[1].trim();
  // cuid()/uuid()/autoincrement() are generated by Prisma/serial — no SQL default.
  if (/^(cuid|uuid|autoincrement)\(/.test(raw)) return '';
  if (raw === 'true' || raw === 'false') return `DEFAULT ${raw}`;
  if (/^-?\d+(\.\d+)?$/.test(raw)) return `DEFAULT ${raw}`;
  if (raw.startsWith('"') && raw.endsWith('"')) return `DEFAULT '${raw.slice(1, -1).replace(/'/g, "''")}'`;
  return '';
}

function parse(text) {
  const tables = [];
  const modelRe = /model\s+(\w+)\s*\{([\s\S]*?)\n\}/g;
  let m;
  while ((m = modelRe.exec(text))) {
    const name = m[1];
    const body = m[2];
    const columns = [];
    const indexes = [];
    let pk = null;
    for (const rawLine of body.split('\n')) {
      const line = stripComment(rawLine).trim();
      if (!line) continue;
      if (line.startsWith('@@')) {
        const uq = line.match(/@@unique\(\[([^\]]+)\]\)/);
        const ix = line.match(/@@index\(\[([^\]]+)\]\)/);
        if (uq) {
          const cols = uq[1].split(',').map((s) => s.trim());
          indexes.push(`CREATE UNIQUE INDEX IF NOT EXISTS "${name}_${cols.join('_')}_key" ON "${name}" (${cols.map((c) => `"${c}"`).join(', ')})`);
        } else if (ix) {
          const cols = ix[1].split(',').map((s) => s.trim());
          indexes.push(`CREATE INDEX IF NOT EXISTS "${name}_${cols.join('_')}_idx" ON "${name}" (${cols.map((c) => `"${c}"`).join(', ')})`);
        }
        continue;
      }
      const fm = line.match(/^(\w+)\s+(\w+)(\[\])?(\?)?\s*(.*)$/);
      if (!fm) continue;
      const [, field, baseType, arr, opt, attrs] = fm;
      if (!(baseType in SCALARS)) continue; // relation field — no column
      const pgType = SCALARS[baseType] + (arr ? '[]' : '');
      const isId = /@id\b/.test(attrs);
      const def = sqlDefault(attrs, Boolean(arr));
      const notNull = !opt || Boolean(arr); // arrays are non-null with '{}' default
      columns.push({ field, pgType, def, notNull, isId });
      if (isId) pk = field;
      if (/@unique\b/.test(attrs)) {
        indexes.push(`CREATE UNIQUE INDEX IF NOT EXISTS "${name}_${field}_key" ON "${name}" ("${field}")`);
      }
    }
    tables.push({ name, columns, indexes, pk });
  }
  return tables;
}

function build(tables) {
  const statements = [];
  // 1) CREATE TABLE IF NOT EXISTS (brand-new tables get created complete)
  for (const t of tables) {
    const cols = t.columns.map((c) => {
      if (c.field === t.pk) return `"${c.field}" ${c.pgType} PRIMARY KEY`;
      return [`"${c.field}"`, c.pgType, c.notNull ? 'NOT NULL' : '', c.def].filter(Boolean).join(' ');
    });
    statements.push(`CREATE TABLE IF NOT EXISTS "${t.name}" (\n  ${cols.join(',\n  ')}\n)`);
  }
  // 2) ALTER ... ADD COLUMN IF NOT EXISTS (existing tables get any missing column,
  //    added nullable+default so it can never fail on a populated table)
  for (const t of tables) {
    const adds = t.columns
      .filter((c) => c.field !== t.pk)
      .map((c) => `ADD COLUMN IF NOT EXISTS "${c.field}" ${[c.pgType, c.def].filter(Boolean).join(' ')}`);
    if (adds.length) statements.push(`ALTER TABLE "${t.name}" ${adds.join(', ')}`);
  }
  // 3) Indexes / unique constraints
  for (const t of tables) for (const ix of t.indexes) statements.push(ix);
  return statements;
}

const text = readFileSync(schemaPath, 'utf8');
const tables = parse(text);

// ── Self-verification (fails the build on any anomaly) ──
const declaredModels = [...text.matchAll(/^model\s+(\w+)\s*\{/gm)].map((m) => m[1]);
const problems = [];
if (tables.length !== declaredModels.length) {
  problems.push(`parsed ${tables.length} models but schema declares ${declaredModels.length}`);
}
for (const t of tables) {
  if (!t.pk) problems.push(`model ${t.name} has no @id primary key column parsed`);
  if (t.columns.length === 0) problems.push(`model ${t.name} parsed zero columns`);
}
if (problems.length) {
  console.error('[generate-schema-ddl] ABORT — schema parse problems:\n  - ' + problems.join('\n  - '));
  process.exit(1);
}

const statements = build(tables);
const banner =
  '// AUTO-GENERATED from prisma/schema.prisma by scripts/generate-schema-ddl.mjs.\n' +
  '// Do NOT edit by hand. Regenerate with: npm run schema:gen\n';
const out = `${banner}export const SCHEMA_STATEMENTS = ${JSON.stringify(statements, null, 2)};\n`;
// Type declaration so TypeScript (incl. Vercel's function compiler) knows the
// generated .js exports a string[] — avoids an implicit-any error on import.
const dts = `${banner}export const SCHEMA_STATEMENTS: string[];\n`;

// In --check mode, fail if either committed file is stale (CI / pre-deploy guard).
if (process.argv.includes('--check')) {
  const read = (p) => { try { return readFileSync(p, 'utf8'); } catch { return ''; } };
  if (read(outPath) !== out || read(dtsPath) !== dts) {
    console.error('[generate-schema-ddl] STALE: generated schema files are out of date. Run: npm run schema:gen');
    process.exit(1);
  }
  console.log(`[generate-schema-ddl] up to date (${statements.length} statements, ${tables.length} tables)`);
} else {
  writeFileSync(outPath, out);
  writeFileSync(dtsPath, dts);
  console.log(`[generate-schema-ddl] wrote ${statements.length} statements for ${tables.length} tables`);
}
